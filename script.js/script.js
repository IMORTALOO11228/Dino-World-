function getImagePath(filename) {
  const currentPath = window.location.pathname;

  if (currentPath.includes("/animals.html/")) {
    return "../" + filename;
  }

  return filename;
}

animals.forEach((animal) => {
  animal.image = getImagePath(animal.image);
});

window.dinoWorldAnimals = animals;

if (animals.length !== 66) {
  console.error("تعداد جانوران باید دقیقاً 66 باشد، اما الان " + animals.length + " مورد است.");
}

document.addEventListener("DOMContentLoaded", () => {
  const list = document.getElementById("animal-list");

  if (!list) return;

  const params = new URLSearchParams(window.location.search);
  const selectedPeriod = params.get("period");

  const filteredAnimals = selectedPeriod
    ? animals.filter((animal) => animal.period === selectedPeriod)
    : animals;

  list.innerHTML = "";

  filteredAnimals.forEach((animal) => {
    const card = document.createElement("a");

    card.href = `../animal.html?name=${encodeURIComponent(animal.name)}`;
    card.className = "period-card animal-card";

    card.innerHTML = `
      <span class="icon">${animal.icon}</span>
      <h3>${animal.name}</h3>
    `;

    list.appendChild(card);
  });

  if (filteredAnimals.length === 0) {
    list.innerHTML = `
      <p>جانوری برای این دوره پیدا نشد.</p>
    `;
  }
});
